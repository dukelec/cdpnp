"""Generate firmware/fw_hashes.json for fw_cfg_update.py

The old firmware in the field reports a git hash in the SW field of its info
string (e.g. "d9529f5", "v2.0-5-gd9529f5", "...-dirty"); the new builds report
"vX.Y" and, where the model string is shared by several hardware lines (cdcam),
a HW field. For the old builds the updater looks the hash up here to tell
which firmware line the module is on, e.g. cdcam1 or cdcam2/3, both "M: cdcam".

A commit belongs to a variant when it is on the first-parent chain of one of
the branch tips listed for that variant: these are the commits that were built
for it. Commits on the chains of several variants are the history before the
branches split: they go to the variant in PRE_SPLIT, or list all of them (the
updater tells them apart by the model string).

Usage: tools/fw_hash_gen.py [FW_REPOS_DIR]   # default: ../../cdbus/fw
"""

import sys, json, subprocess
from os.path import join as pjoin, dirname, abspath

HERE = dirname(abspath(__file__))

# family: (repo dir, {variant: [branch tips]})
FAMILIES = {
    'cdstep': ('cdstep', {
        'step':     ['origin/hw3.x_support', 'origin/master'],
        'step_r':   ['origin/r_axis', 'origin/r_axis_cdnet_v1'],
        'step_z':   ['origin/z_axis', 'origin/z_axis_cdnet_v1'],
        'step_hw2': ['origin/hw2.0_old'],               # not supported by the current firmware
    }),
    'cdcam': ('cdcam', {
        'cam1':  ['github/hw1.old_support', 'github/hw_v1'],
        'cam23': ['github/hw2.x_support', 'github/hw_v3'],
        'cam4':  ['github/master'],                     # esp32 based, not handled by this updater
    }),
    'cdpump2': ('cdpump', {
        'pump2': ['origin/master'],
    }),
    'cdpump1': ('cdpump_g031_v1', {
        'pump1': ['master'],
    }),
}

# the history before the hw 2.0 branch (2023-04) was built for hw v1 only
PRE_SPLIT = {
    'cdcam': ('cam1', {'cam1', 'cam23'}),
}

# builds shipped in tools/firmware whose commits are no longer on any branch (rebuilt branches)
EXTRA = {
    'cdstep': {
        'step_z': ['90db4d7', 'a49d731', '984a756', 'efbb9a9'],
        'step_r': ['d4f7549', '5e0418f', '5721673', '72abac5'],
    },
}


def git(repo, *args):
    return subprocess.run(['git', '-C', repo] + list(args), check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.DEVNULL).stdout.decode()


def main():
    fw_dir = abspath(sys.argv[1] if len(sys.argv) > 1 else pjoin(HERE, '..', '..', 'cdbus', 'fw'))
    out = {'_doc': 'generated by tools/fw_hash_gen.py, do not edit', 'hash': {}}
    for family, (repo_name, variants) in FAMILIES.items():
        repo = pjoin(fw_dir, repo_name)
        hashes = {}     # full hash -> set of variants
        for variant, tips in variants.items():
            for tip in tips:
                try:
                    revs = git(repo, 'rev-list', '--first-parent', tip).split()
                except subprocess.CalledProcessError:
                    print(f'warning: {repo_name}: {tip} not found, skipped')
                    continue
                for h in revs:
                    hashes.setdefault(h, set()).add(variant)
        if family in PRE_SPLIT:
            to, shared = PRE_SPLIT[family]
            for h, v in hashes.items():
                if v == shared:
                    hashes[h] = {to}
        for variant, revs in EXTRA.get(family, {}).items():
            for r in revs:
                h = git(repo, 'rev-parse', r).strip()
                hashes.setdefault(h, set()).add(variant)
        out['hash'][family] = {h: sorted(v) for h, v in sorted(hashes.items())}
        count = {}
        for v in hashes.values():
            count['/'.join(sorted(v))] = count.get('/'.join(sorted(v)), 0) + 1
        print(f'{family}: {len(hashes)} commits: {count}')

    path = pjoin(HERE, 'firmware', 'fw_hashes.json')
    with open(path, 'w') as f:
        json.dump(out, f, indent=1, sort_keys=True)
        f.write('\n')
    print(f'written: {path}')


if __name__ == '__main__':
    main()
